// Writes engine/tests/library.inc from data/songs.json so the native tests run
// against exactly the library the app ships.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseNotes } from './notation.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { songs } = JSON.parse(readFileSync(resolve(root, 'data/songs.json'), 'utf8'));

const escape = (s) => JSON.stringify(s);
const lines = songs.map((song) => {
  const notes = parseNotes(song.notes);
  const midi = notes.map((n) => n.midi.toFixed(1) + 'f').join(', ');
  const beats = notes.map((n) => n.beats.toFixed(2) + 'f').join(', ');
  return `  {${escape(song.title)}, ${escape(song.composer)}, {${midi}}, {${beats}}},`;
});

const out = resolve(root, 'engine/tests/library.inc');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/gen-test-library.mjs from data/songs.json. Do not edit.\n${lines.join('\n')}\n`);
console.log(`library.inc: ${songs.length} songs`);
